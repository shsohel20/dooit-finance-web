import countriesAlpha3 from "./countries-alpha3.json";

// ── ISO country lookup (name / alpha2 / alpha3) ──────────────────────────────
// Backed by countries-alpha3.json (198 entries). Keyed by both alpha-2 and
// alpha-3 codes (upper-cased) for O(1) resolution.
const COUNTRY_BY_CODE = countriesAlpha3.reduce((acc, c) => {
  if (c.alpha2) acc[c.alpha2.toUpperCase()] = c;
  if (c.alpha3) acc[c.alpha3.toUpperCase()] = c;
  return acc;
}, {});

// Regional-indicator flag emoji from an ISO alpha-2 code.
export const flagEmoji = (alpha2) =>
  alpha2 && alpha2.length === 2
    ? String.fromCodePoint(
        ...[...alpha2.toUpperCase()].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65),
      )
    : "";

/**
 * Resolve an ISO alpha-2 or alpha-3 country code to a display name + flag.
 * Unknown codes fall back to the raw (upper-cased) value with no flag.
 * @param {string} code e.g. "AUS" | "AU"
 * @returns {{ name: string, alpha2: string, flag: string }}
 */
export const resolveCountry = (code) => {
  if (!code) return { name: "—", alpha2: "", flag: "" };
  const upper = String(code).toUpperCase();
  const hit = COUNTRY_BY_CODE[upper];
  const alpha2 = hit?.alpha2 ?? (upper.length === 2 ? upper : "");
  return { name: hit?.name ?? upper, alpha2, flag: flagEmoji(alpha2) };
};

